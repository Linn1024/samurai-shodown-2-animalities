"""Map existing sprite colors to native Ukyo palette entries, without changing art."""
from pathlib import Path
import sys,json
sys.path.insert(0,str(Path('tools/pillow').resolve()))
from PIL import Image

root=Path('assets/ukyo-animality')
rom=bytearray(Path('work/hack/063sp.p2').read_bytes())
rom[0::2],rom[1::2]=rom[1::2],rom[0::2]
words=[int.from_bytes(rom[a:a+2],'big') for a in range(0x14600,0x14700,2)]
def lut(resistors):
    weights=[255/r/sum(1/x for x in resistors) for r in resistors]
    return [int(sum(w*((v>>i)&1) for i,w in enumerate(weights))+.5) for v in range(1<<len(weights))]
hb=lut([3900,2200,1000,470,220])
fb=lut([8200,3900,2200,1000,470,220])
def channels(w):
    return [(w>>8&15)*2+(w>>14&1),(w>>4&15)*2+(w>>13&1),(w&15)*2+(w>>12&1)]
colors=[tuple(hb[v] for v in channels(w)) for w in words]
used=sorted({p[:3] for i in range(16) for p in Image.open(root/f'frame-{i:02d}.png').convert('RGBA').get_flattened_data() if p[3]})
mapping=[]
for color in used:
    candidates=[i for i in range(128) if i%16!=0]
    index=min(candidates,key=lambda i:sum((color[k]-colors[i][k])**2 for k in range(3)))
    mapping.append([*color,index,words[index]])
native={p[:3] for p in Image.open(root/'native-idle.png').convert('RGBA').get_flattened_data() if p[3]}
assert all(c in colors for c in native),'all original human colors must map exactly'
lines=['-- Generated by reports/build-animality-palette-map.py. Indices are zero based.',
       '-- FBNeo RGB resistor conversion: src/burn/drv/neogeo/neo_palette.cpp.',
       'return {rgb={'+','.join(map(str,fb))+'},colors={']
lines += [' {'+','.join(map(str,row))+'},' for row in mapping]
lines += ['}}']
(root/'palette-map.lua').write_text('\n'.join(lines)+'\n')
(root/'palette-map.json').write_text(json.dumps({'source_palette':'Ukyo default, ROM 0x214600','colors':mapping,'human_colors_exact':len(native),'fbneo_rgb_lut':fb},indent=2))
print(f'Mapped {len(used)} sprite colors; all {len(native)} native human colors matched exactly.')
