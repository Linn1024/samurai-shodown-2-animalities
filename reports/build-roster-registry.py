"""Enable only animalities with a complete built asset set."""
from pathlib import Path
import json,sys,re,argparse
sys.path.insert(0,str(Path('tools/pillow').resolve()))
from PIL import Image
parser=argparse.ArgumentParser()
parser.add_argument('--existing-only',action='store_true',help='Refresh enabled definitions without enabling untested assets')
parser.add_argument('--output',default='animalities.lua')
args=parser.parse_args()
existing=set(re.findall(r"slug='([^']+)'",Path('animalities.lua').read_text())) if args.existing_only else None
roster=json.loads(Path('assets/native-roster/roster.json').read_text())
flying={'ukyo','nakoruru','charlotte','gen-an','nicotine','kuroko'}
lines=['-- Generated by reports/build-roster-registry.py; only complete built assets are enabled.','return {']
enabled=[]
for r in roster:
 slug=r['slug'];root=Path('assets')/(slug+'-animality')
 if existing is not None and slug not in existing:continue
 if not (root/'asset-manifest.json').exists() or not (root/'palette-map.lua').exists():continue
 if len(list((root/'gd').glob('*.gd')))!=160:continue
 meta=json.loads((root/'asset-manifest.json').read_text())
 size=meta['cell'][0];anchor=meta['anchor']
 im=Image.open(root/'frame-08.png').convert('RGBA')
 box=im.getbbox();contact_x=box[2]-1-anchor[0]
 ys=[y for y in range(im.height) for x in range(box[2]-3,box[2]) if im.getpixel((x,y))[3]]
 contact_y=anchor[1]-sorted(ys)[len(ys)//2]
 movement='flight' if slug in flying else 'crouch_pounce'
 config_path=root/'build-config.json'
 if config_path.exists():
  config=json.loads(config_path.read_text())
  movement=config.get('movement',movement)
  contact_x,contact_y=config.get('contact',(contact_x,contact_y))
 name=r['name'].split()[0]+' '+r['animal']
 lines.append(f" [0x{r['id']:02x}]={{name='{name}',character='{r['name']}',palette=0x{r['palette']:x},slug='{slug}',frames=16,movement='{movement}',contact_x={contact_x},contact_y={contact_y},victory=0x600,canvas={size},anchor={{{anchor[0]},{anchor[1]}}}}},")
 enabled.append(r)
lines+=['}']
Path(args.output).write_text('\n'.join(lines)+'\n')
if args.output=='animalities.lua':Path('reports/animality-enabled-roster.json').write_text(json.dumps(enabled,indent=2))
print('Enabled '+str(len(enabled))+' animalities: '+', '.join(r['slug'] for r in enabled))
